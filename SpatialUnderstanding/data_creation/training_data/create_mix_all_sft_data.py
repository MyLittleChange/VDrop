"""
Create mixed SFT training data from existing panorama + V4 + V5 samples.

Three data sources:
  Existing: panorama_train_samples_filtered.json (panoramas in rendered_panorama_train/)
  V4: dataset_*_filtered_V4_normalized.json (panoramas in rendered_panorama_v4/)
  V5: dataset_*_filtered_V5_normalized.json (panoramas in rendered_panorama_v5/)

Supports four thinking modes:
  --thinking_mode visual_only (default)
    3 images: [cam0, cam1, panorama] → Parquet files
    Panorama is generated as intermediate thinking output.
    Skips samples without rendered panorama.

  --thinking_mode no_thinking
    2 images: [cam0, cam1] → JSONL (ShareGPT format)
    All samples included (no panorama needed).

  --thinking_mode understanding
    3 images: [cam0, cam1, panorama] as input → JSONL (ShareGPT format)
    Panorama provided as input context, output is answer only.
    Skips samples without rendered panorama.

  --thinking_mode text_thinking
    Reads pre-annotated per-category JSONL files from --text_thinking_source_dir
    (generated by annotate_text_reasoning.py) and merges them into
    text_thinking/text_thinking.jsonl. No raw data loading performed.

  --thinking_mode interleaved
    Combines text-thinking + visual-thinking. Builds a (sample_id, question)
    → think_text lookup from the same per-category files used by text_thinking,
    then runs the visual_only image pipeline. Each row's first output text is
    "<think>{text}</think><image_start>" instead of just "<image_start>".
    Output: sharded parquet files in <output_dir>/interleaved/.
    Samples missing a think trace OR a panorama are skipped.

Usage:
    python SpatialUnderstanding/data_creation/training_data/create_mix_all_sft_data.py
    python SpatialUnderstanding/data_creation/training_data/create_mix_all_sft_data.py \\
        --thinking_mode no_thinking
    python SpatialUnderstanding/data_creation/training_data/create_mix_all_sft_data.py \\
        --thinking_mode understanding
"""

