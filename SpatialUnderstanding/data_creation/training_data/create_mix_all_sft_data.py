def load_samples(filepath: str) -> list:
    if not os.path.exists(filepath):
        print(f"  [SKIP] Not found: {filepath}")
        return []
    with open(filepath, "r") as f:
        data = json.load(f)
    print(f"  Loaded {len(data)} samples from {os.path.basename(filepath)}")
    return data


def main():
    parser = argparse.ArgumentParser(
        description="Create mixed SFT training data from existing + V4 + V5 samples"
    )
    # Existing
    parser.add_argument("--existing_train_file", default=EXISTING_TRAIN_FILE)
    parser.add_argument("--existing_mapping_file", default=EXISTING_MAPPING_FILE)
    parser.add_argument("--existing_panorama_dir", default=EXISTING_PANORAMA_DIR)
    # V4
    parser.add_argument("--v4_train_files", nargs="+", default=V4_TRAIN_FILES)
    parser.add_argument("--v4_mapping_file", default=V4_MAPPING_FILE)
    parser.add_argument("--v4_panorama_dir", default=V4_PANORAMA_DIR)
    # V5
    parser.add_argument("--v5_train_files", nargs="+", default=V5_TRAIN_FILES)
    parser.add_argument("--v5_mapping_file", default=V5_MAPPING_FILE)
    parser.add_argument("--v5_panorama_dir", default=V5_PANORAMA_DIR)
    # Output
    parser.add_argument("--output_dir", default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--thinking_mode",
        choices=["visual_only", "no_thinking", "understanding", "json_export", "text_thinking", "interleaved"],
        default="visual_only",
    )
    parser.add_argument(
        "--text_thinking_source_dir",
        default=None,
        help="Dir containing per-category annotated JSONL files for text_thinking mode. "
             "Defaults to <output_dir>/text_thinking/",
    )
    parser.add_argument(
        "--interleaved_text_dir",
        default=None,
        help="Dir containing per-category annotated JSONL files for interleaved mode. "
             "Defaults to <output_dir>/text_thinking/",
    )
    parser.add_argument("--max_workers", type=int, default=32)
    parser.add_argument("--rows_per_group", type=int, default=10)
    parser.add_argument("--groups_per_file", type=int, default=10)
    parser.add_argument(
        "--image_root_dir",
        default="/network/scratch",
        help="Root dir for relative image paths (no_thinking mode only)",
    )
    parser.add_argument("--rotation_qa_dir", default=ROTATION_QA_DIR)
    parser.add_argument("--no_rotation", action="store_true", default=False,
                        help="Exclude rotation QA from training data")
    parser.add_argument("--max_relative_distance", type=int, default=3000,
                        help="Max relative_distance questions to include (default: 3000). Set 0 for no cap.")
    parser.add_argument("--max_perspective_taking", type=int, default=3000,
                        help="Max perspective_taking+spatial_orientation combined (split 50/50, default: 3000). Set 0 for no cap.")
    parser.add_argument("--filter_subset", action=argparse.BooleanOptionalAction, default=False,
                        help="Keep only anchor + counting + relative distance (anchor-based closest/farthest "
                             "and camera-based closest_to_camera_*/farthest_from_camera_*). "
                             "Applied AFTER seeded sampling to preserve selection determinism.")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--prefix_ids",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Prefix sample_id with its source ('v4_'/'v5_'/'ankur_') so V4/V5/ankur "
             "namespaces no longer collide. Default: True.",
    )
    args = parser.parse_args()

    random.seed(args.seed)
    output_dir = os.path.join(args.output_dir, args.thinking_mode)
    print(f"Thinking mode: {args.thinking_mode}")
    print(f"Output dir: {output_dir}")

    # ── text_thinking: merge pre-annotated per-category files ────────────────
    if args.thinking_mode == "text_thinking":
        TEXT_THINKING_CATEGORIES = [
            "counting", "anchor", "relative_distance", "spatial", "perspective_taking",
        ]
        source_dir = args.text_thinking_source_dir or os.path.join(
            args.output_dir, "text_thinking"
        )
        print(f"Reading annotated files from: {source_dir}")
        all_data = []
        counts = {}
        for cat in TEXT_THINKING_CATEGORIES:
            path = os.path.join(source_dir, f"{cat}.jsonl")
            if not os.path.exists(path):
                print(f"  [skip] {path} missing")
                continue
            rows = [json.loads(ln) for ln in open(path)]
            for row in rows:
                convs = row.get("conversations", [])
                if convs and convs[0].get("from") == "human":
                    convs[0]["value"] = convs[0]["value"].replace(
                        NO_THINKING_SYSTEM_PROMPT, TEXT_THINKING_SYSTEM_PROMPT
                    )
            counts[cat] = len(rows)
            all_data.extend(rows)
            print(f"  {cat}: {len(rows)} rows")
        random.shuffle(all_data)
        out_dir = os.path.join(args.output_dir, "text_thinking")
        os.makedirs(out_dir, exist_ok=True)
        out_file = os.path.join(out_dir, "text_thinking.jsonl")
        with open(out_file, "w") as f:
            for item in all_data:
                f.write(json.dumps(item) + "\n")
        manifest = {
            "output": out_file,
            "total_rows": len(all_data),
            "rows_per_category": counts,
        }
        with open(os.path.join(out_dir, "manifest.json"), "w") as f:
            json.dump(manifest, f, indent=2)
        print(f"\nDone! {len(all_data)} rows → {out_file}")
        return

    # Load existing samples
    print(f"\nLoading existing panorama training samples...")
    existing_samples = load_samples(args.existing_train_file)

    # Load V4 samples
    print(f"\nLoading V4 training samples...")
    v4_samples = []
    for filepath in args.v4_train_files:
        v4_samples.extend(load_samples(filepath))
    print(f"  Total V4: {len(v4_samples)} samples")

    # Load V5 samples
    print(f"\nLoading V5 training samples...")
    v5_samples = []
    for filepath in args.v5_train_files:
        v5_samples.extend(load_samples(filepath))
    print(f"  Total V5: {len(v5_samples)} samples")

    # Load rotation QA samples
    rotation_samples = []
    if not args.no_rotation:
        print("\nLoading rotation QA samples...")
        rotation_samples = load_rotation_samples(args.rotation_qa_dir)
        print(f"  Rotation QA: {len(rotation_samples)} samples")

    all_samples = existing_samples + v4_samples + v5_samples
    print(f"\nTotal combined (non-rotation): {len(all_samples)} samples")

    # Load mappings
    existing_mapping = {}
    if os.path.exists(args.existing_mapping_file):
        with open(args.existing_mapping_file, "r") as f:
            existing_mapping = json.load(f)
        print(f"Existing mapping: {len(existing_mapping)} scenes")

    v4_mapping = {}
    if os.path.exists(args.v4_mapping_file):
        with open(args.v4_mapping_file, "r") as f:
            v4_mapping = json.load(f)
        print(f"V4 mapping: {len(v4_mapping)} scenes")

    v5_mapping = {}
    if os.path.exists(args.v5_mapping_file):
        with open(args.v5_mapping_file, "r") as f:
            v5_mapping = json.load(f)
        print(f"V5 mapping: {len(v5_mapping)} scenes")

    # Filter samples with valid questions
    all_samples = [s for s in all_samples if s.get("question_both_views", "").strip()]
    print(f"After question filter: {len(all_samples)} samples")

    # Filter out samples with bad panoramas (if blacklist exists)
    bad_panoramas = set()
    if os.path.exists(BAD_PANORAMAS_FILE):
        with open(BAD_PANORAMAS_FILE) as f:
            bad_panoramas = set(json.load(f).get("bad_panoramas", []))
        print(f"Loaded {len(bad_panoramas)} bad panoramas from blacklist")

        def _has_bad_panorama(sample):
            path = resolve_panorama_path(
                sample, existing_mapping, v4_mapping, v5_mapping,
                args.existing_panorama_dir, args.v4_panorama_dir, args.v5_panorama_dir
            )
            return path in bad_panoramas

        before = len(all_samples)
        all_samples = [s for s in all_samples if not _has_bad_panorama(s)]
        print(f"After bad panorama filter: {len(all_samples)} samples (removed {before - len(all_samples)})")

    # Source-prefix sample_ids so V4/V5/ankur namespaces stop colliding.
    # Apply BEFORE caps/shuffles so prefixed ids propagate everywhere downstream.
    if args.prefix_ids:
        n_prefixed = 0
        n_unknown = 0
        for s in all_samples:
            sid = s.get("sample_id", "")
            new_sid = prefixed_sample_id(s)
            if new_sid != sid:
                s["sample_id"] = new_sid
                n_prefixed += 1
            elif sid and not new_sid.startswith(SOURCE_PREFIXES):
                n_unknown += 1
        print(f"prefix_ids: prefixed {n_prefixed}, unknown source for {n_unknown}")

    # Balance relative_distance questions: sample max_relative_distance/2 from each group.
    # Group 1 (anchor): closest + farthest (object-anchor questions)
    # Group 2 (camera): closest_to_camera_* + farthest_from_camera_* (camera-position questions)
    if args.max_relative_distance > 0:
        anchor_types = {"closest", "farthest", "relative_distance"}
        camera_types = {"closest_to_camera_1", "closest_to_camera_2",
                        "farthest_from_camera_1", "farthest_from_camera_2"}
        anchor_qs = [s for s in all_samples if s.get("question_type") in anchor_types]
        camera_qs = [s for s in all_samples if s.get("question_type") in camera_types]
        other = [s for s in all_samples if s.get("question_type") not in anchor_types | camera_types]
        n_each = args.max_relative_distance // 2
        if len(anchor_qs) > n_each:
            anchor_qs = random.sample(anchor_qs, n_each)
        if len(camera_qs) > n_each:
            camera_qs = random.sample(camera_qs, n_each)
        print(f"relative_distance: {len(anchor_qs)} anchor + {len(camera_qs)} camera = {len(anchor_qs)+len(camera_qs)} total (cap={args.max_relative_distance})")
        all_samples = other + anchor_qs + camera_qs

    # Cap perspective_taking + spatial_orientation combined to max_perspective_taking total, split 50/50
    if args.max_perspective_taking > 0:
        persp_qs = [s for s in all_samples if s.get("question_type") == "perspective_taking"]
        spatial_qs = [s for s in all_samples if s.get("question_type") == "spatial_orientation"]
        other = [s for s in all_samples if s.get("question_type") not in ("perspective_taking", "spatial_orientation")]
        n_each = args.max_perspective_taking // 2
        if len(persp_qs) > n_each:
            persp_qs = random.sample(persp_qs, n_each)
        if len(spatial_qs) > n_each:
            spatial_qs = random.sample(spatial_qs, n_each)
        print(f"perspective_taking+spatial_orientation: {len(persp_qs)}+{len(spatial_qs)}={len(persp_qs)+len(spatial_qs)} total (cap={args.max_perspective_taking})")
        all_samples = other + persp_qs + spatial_qs

    # Subset filter: keep only anchor + counting + relative distance (anchor-based and camera-based).
    # Runs AFTER the seeded sampling above so selection of which rows survive is deterministic.
    if args.filter_subset:
        keep_types = {
            "anchor", "counting",
            "closest", "farthest",
            "closest_to_camera_1", "closest_to_camera_2",
            "farthest_from_camera_1", "farthest_from_camera_2",
        }
        before = len(all_samples)
        all_samples = [s for s in all_samples if s.get("question_type") in keep_types]
        print(f"After filter_subset (keep {sorted(keep_types)}): {len(all_samples)} samples (removed {before - len(all_samples)})")

    # Category breakdown (before processing)
    category_counts = {}
    for s in all_samples + rotation_samples:
        qtype = s.get("question_type", "unknown")
        category_counts[qtype] = category_counts.get(qtype, 0) + 1
    print("\nCategory breakdown:")
    for cat, count in sorted(category_counts.items()):
        print(f"  {cat}: {count}")

    # Select processor
    if args.thinking_mode == "no_thinking":
        process_fn = partial(process_item_no_thinking, image_root_dir=args.image_root_dir)
        process_fn_rotation = partial(process_item_no_thinking_rotation, image_root_dir=args.image_root_dir)
    elif args.thinking_mode == "understanding":
        process_fn = partial(
            process_item_understanding,
            existing_mapping=existing_mapping,
            v4_mapping=v4_mapping,
            v5_mapping=v5_mapping,
            existing_panorama_dir=args.existing_panorama_dir,
            v4_panorama_dir=args.v4_panorama_dir,
            v5_panorama_dir=args.v5_panorama_dir,
            image_root_dir=args.image_root_dir,
        )
        process_fn_rotation = partial(process_item_understanding_rotation, image_root_dir=args.image_root_dir)
    elif args.thinking_mode == "json_export":
        images_dir = os.path.join(output_dir, "images")
        os.makedirs(images_dir, exist_ok=True)
        process_fn = partial(
            process_item_json_export,
            existing_mapping=existing_mapping,
            v4_mapping=v4_mapping,
            v5_mapping=v5_mapping,
            existing_panorama_dir=args.existing_panorama_dir,
            v4_panorama_dir=args.v4_panorama_dir,
            v5_panorama_dir=args.v5_panorama_dir,
            images_dir=images_dir,
        )
        process_fn_rotation = partial(process_item_json_export_rotation, images_dir=images_dir)
    elif args.thinking_mode == "interleaved":
        text_dir = args.interleaved_text_dir or os.path.join(args.output_dir, "text_thinking")
        cat_files = [os.path.join(text_dir, f"{c}.jsonl")
                     for c in ["counting", "anchor", "relative_distance", "spatial", "perspective_taking"]]
        print(f"\nBuilding think_lookup from {text_dir}")
        think_lookup = build_think_lookup(cat_files)
        print(f"  think_lookup: {len(think_lookup)} (sample_id, question) keys")
        process_fn = partial(
            process_item_interleaved,
            existing_mapping=existing_mapping,
            v4_mapping=v4_mapping,
            v5_mapping=v5_mapping,
            existing_panorama_dir=args.existing_panorama_dir,
            v4_panorama_dir=args.v4_panorama_dir,
            v5_panorama_dir=args.v5_panorama_dir,
            think_lookup=think_lookup,
        )
        process_fn_rotation = partial(process_item_interleaved_rotation, think_lookup=think_lookup)
    else:
        process_fn = partial(
            process_item_visual_only,
            existing_mapping=existing_mapping,
            v4_mapping=v4_mapping,
            v5_mapping=v5_mapping,
            existing_panorama_dir=args.existing_panorama_dir,
            v4_panorama_dir=args.v4_panorama_dir,
            v5_panorama_dir=args.v5_panorama_dir,
        )
        process_fn_rotation = process_item_visual_only_rotation

    # Process non-rotation samples in parallel
    print(f"\nProcessing {len(all_samples)} samples with {args.max_workers} workers...")
    with ThreadPoolExecutor(max_workers=args.max_workers) as executor:
        processed = list(tqdm(executor.map(process_fn, all_samples), total=len(all_samples)))
    all_data = [res for res in processed if res is not None]

    # Process rotation samples in parallel
    if rotation_samples:
        print(f"\nProcessing {len(rotation_samples)} rotation QA samples...")
        with ThreadPoolExecutor(max_workers=args.max_workers) as executor:
            processed_rot = list(tqdm(executor.map(process_fn_rotation, rotation_samples), total=len(rotation_samples)))
        all_data += [res for res in processed_rot if res is not None]

    random.shuffle(all_data)
    print(f"Successfully processed: {len(all_data)} samples")

    if len(all_data) == 0:
        print("No samples to write. Exiting.")
        return

    os.makedirs(output_dir, exist_ok=True)

    if args.thinking_mode in ("no_thinking", "understanding"):
        jsonl_file = os.path.join(output_dir, f"{args.thinking_mode}.jsonl")
        print(f"Writing JSONL to {jsonl_file}")
        with open(jsonl_file, "w") as f:
            for item in all_data:
                f.write(json.dumps(item) + "\n")
        print(f"\nDone! {len(all_data)} samples → {jsonl_file}")

    elif args.thinking_mode == "json_export":
        json_file = os.path.join(output_dir, "training_data.json")
        print(f"Writing JSON to {json_file}")
        with open(json_file, "w") as f:
            json.dump(all_data, f, indent=2)
        print(f"\nDone! {len(all_data)} samples → {json_file}")

    else:
        # Remove sample_id before writing parquet
        for item in all_data:
            item.pop("sample_id", None)

        schema = pa.schema([
            pa.field("image_list", pa.list_(pa.binary())),
            pa.field("instruction_list", pa.list_(pa.string())),
            pa.field("output_text_list", pa.list_(pa.string())),
        ])

        rows_per_file = args.rows_per_group * args.groups_per_file
        file_index = 0
        parquet_info = {}

        print(f"Writing parquet files to {output_dir}")
        for i in tqdm(range(0, len(all_data), rows_per_file)):
            file_data = all_data[i:i + rows_per_file]
            parquet_file = os.path.join(output_dir, f"chunk_{file_index}.parquet")
            file_index += 1

            num_row_groups = 0
            with pq.ParquetWriter(parquet_file, schema=schema, version="2.6") as writer:
                for j in range(0, len(file_data), args.rows_per_group):
                    group_data = file_data[j:j + args.rows_per_group]
                    group_table = pa.Table.from_pylist(group_data, schema=schema)
                    writer.write_table(group_table)
                    num_row_groups += 1

            parquet_info[parquet_file] = {
                "num_row_groups": num_row_groups,
                "num_rows": len(file_data),
            }

        parquet_info_path = os.path.join(output_dir, "parquet_info.json")
        with open(parquet_info_path, "w") as f:
            json.dump(parquet_info, f, indent=2)

        print(f"\nDone! {len(all_data)} samples → {file_index} parquet file(s) in {output_dir}")
        print(f"Parquet info: {parquet_info_path}")


if __name__ == "__main__":
    main()
