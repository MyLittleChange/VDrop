def process_item_understanding(sample: dict,
                                existing_mapping: dict, v4_mapping: dict, v5_mapping: dict,
                                existing_panorama_dir: str, v4_panorama_dir: str, v5_panorama_dir: str,
                                image_root_dir: str):
    """Understanding: 3 images (cam0, cam1, panorama) as input → JSONL row with answer only."""
    try:
        sample_id = sample.get("sample_id", "")
        question, options, answer_text = get_question_and_answer(sample)

        if not question or not answer_text:
            print(f"[WARNING] Missing question or answer for {sample_id}")
            return None

        img1_path = remap_path(sample.get("user_1_image_local_path"))
        img2_path = remap_path(sample.get("user_2_image_local_path"))
        panorama_path = resolve_panorama_path(
            sample, existing_mapping, v4_mapping, v5_mapping,
            existing_panorama_dir, v4_panorama_dir, v5_panorama_dir
        )

        if not all([img1_path, img2_path, panorama_path]):
            return None
        for img_path in [img1_path, img2_path, panorama_path]:
            if not os.path.exists(img_path):
                return None

        rel_img1 = os.path.relpath(img1_path, image_root_dir)
        rel_img2 = os.path.relpath(img2_path, image_root_dir)
        rel_panorama = os.path.relpath(panorama_path, image_root_dir)

        if options:
            options_str = "\n".join([f"{chr(65 + i)}) {opt}" for i, opt in enumerate(options)])
            full_question = f"{question}\n\n{options_str}"
        else:
            full_question = question

        user_message = f"{UNDERSTANDING_SYSTEM_PROMPT}\n\n<image><image><image>\n{full_question}"
        assistant_response = f"<answer>{answer_text}</answer>"

        return {
            "conversations": [
                {"from": "human", "value": user_message},
                {"from": "gpt", "value": assistant_response},
            ],
            "image": [rel_img1, rel_img2, rel_panorama],
            "id": sample_id,
        }

    except Exception as e:
        print(f"[ERROR] {sample.get('sample_id', 'unknown')}: {e}")
        import traceback
        traceback.print_exc()
        return None


