THINK_RE = re.compile(r"<think>(.*?)</think>", re.DOTALL)
ID_SUFFIX_RE = re.compile(r"_[a-z]+$")


def _extract_human_question(human_val: str) -> str:
    last = human_val.rfind("<image>")
    tail = human_val[last + len("<image>"):] if last != -1 else human_val
    return tail.lstrip("\n").strip()


def _strip_id_suffix(sid: str) -> str:
    """Remove trailing _a/_b/... suffix (added by rekey_text_thinking_dups.py)."""
    return ID_SUFFIX_RE.sub("", sid) if sid else sid


def build_think_lookup(jsonl_paths):
    """Returns {(base_sample_id, question_text): think_text}.
    Base id strips any _a/_b/... suffix; question text disambiguates the rest."""
    lookup = {}
    n_collide = 0
    for p in jsonl_paths:
        if not os.path.exists(p):
            print(f"  [skip] {p} missing")
            continue
        with open(p) as f:
            for ln in f:
                row = json.loads(ln)
                sid = _strip_id_suffix(row.get("id"))
                convs = row.get("conversations", [])
                human = next((c["value"] for c in convs if c.get("from") == "human"), "")
                gpt   = next((c["value"] for c in convs if c.get("from") == "gpt"),   "")
                m = THINK_RE.search(gpt)
                if not (sid and m):
                    continue
                key = (sid, _extract_human_question(human))
                if key in lookup:
                    n_collide += 1
                    continue
                lookup[key] = m.group(1).strip()
    if n_collide:
        print(f"  [warn] {n_collide} colliding (sample_id, question) keys; first wins")
    return lookup


def lookup_think(think_lookup, sample_id, question):
    qn = (question or "").strip()
    sid = sample_id or ""
    if (sid, qn) in think_lookup:
        return think_lookup[(sid, qn)]
    for (k_sid, k_q), think in think_lookup.items():
        if k_sid != sid:
            continue
        if k_q.startswith(qn) or qn.startswith(k_q):
            return think
    return None

